// Regenerate the pinned Unicode table without adding a runtime data dependency:
// curl -fsS https://www.unicode.org/Public/17.0.0/ucd/extracted/DerivedJoiningType.txt -o /tmp/DerivedJoiningType.txt
// node scripts/generate-joining-types.mjs /tmp/DerivedJoiningType.txt
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const source = readFileSync(process.argv[2], "utf8");
if (!source.startsWith("# DerivedJoiningType-17.0.0.txt")) throw new Error("Expected Unicode 17.0.0 DerivedJoiningType.txt");
const ranges = [...source.matchAll(/^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([CDLRT])/gm)]
  .map(([, a, b, type]) => [parseInt(a, 16), parseInt(b ?? a, 16), type])
  .sort((a, b) => a[0] - b[0]);
const rows = ranges.map(([a, b, t]) => `  [0x${a.toString(16)}, 0x${b.toString(16)}, "${t}"],`).join("\n");
writeFileSync(new URL("../engine/src/lettering/joining-types.ts", import.meta.url), `/**
 * Generated by scripts/generate-joining-types.mjs; do not edit the ranges by hand.
 * Unicode 17.0.0: https://www.unicode.org/Public/17.0.0/ucd/extracted/DerivedJoiningType.txt
 * Source SHA-256: ${createHash("sha256").update(source).digest("hex")}
 * Copyright © 2025 Unicode, Inc. Unicode License V3 (see NOTICE.md).
 * Includes transparent characters outside Arabic so they do not interrupt joining.
 */
export type JoiningType = "U" | "C" | "D" | "L" | "R" | "T";

const ranges: readonly (readonly [number, number, JoiningType])[] = [
${rows}
];

/** Unicode Joining_Type; unlisted characters are non-joining (U). */
export function joiningType(char: string): JoiningType {
  const cp = char.codePointAt(0)!;
  let lo = 0;
  let hi = ranges.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >>> 1;
    const [start, end, type] = ranges[mid];
    if (cp < start) hi = mid - 1;
    else if (cp > end) lo = mid + 1;
    else return type;
  }
  return "U";
}
`);
