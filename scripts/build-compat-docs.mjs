// Builds the compatibility docs from data in the repo. Deterministic: same inputs, same bytes.
//
//   node scripts/build-compat-docs.mjs          write docs/compatibility.md, docs/compat.json and the
//                                               "Works with" block in README.md
//   node scripts/build-compat-docs.mjs --check  exit 1 if any of those would change (used in CI)
//
// Inputs: data/compat/machines.json, data/compat/formats.json, data/threads/index.json,
//         engine/src/hoops/library.json and FORMAT_EXTENSIONS in engine/src/formats/types.ts.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const read = (p) => readFileSync(`${ROOT}${p}`, "utf8");
const json = (p) => JSON.parse(read(p));

const ISSUE_URL = "https://github.com/Kadwood/lilo/issues/new?template=machine-report.yml";
const README_START = "<!-- compat:start (generated by scripts/build-compat-docs.mjs, do not edit by hand) -->";
const README_END = "<!-- compat:end -->";
const WIFI_PENDING = "Wi-Fi send tested on: none yet. Brother NV2700 test pending.";

/** Extensions Lilo reads and writes, taken from the engine source so the docs cannot drift. */
export function liloExtensions(typesSource) {
  const m = typesSource.match(/FORMAT_EXTENSIONS\s*=\s*\[([^\]]*)\]/);
  if (!m) throw new Error("FORMAT_EXTENSIONS not found in engine/src/formats/types.ts");
  return [...m[1].matchAll(/"([a-z0-9]+)"/g)].map((x) => x[1]).sort();
}

const inch = (mm) => {
  const v = Math.round((mm / 25.4) * 100) / 100;
  return String(v);
};
const esc = (s) => String(s).replace(/\|/g, "\\|");
const ext = (e) => `.${e}`;
const list = (a) => (a.length ? a.join(", ") : "none");
const yesNo = (b) => (b ? "yes" : "no");

function wifiLabel(v) {
  return v === true ? "yes" : v === "untested" ? "untested" : "no";
}

function table(head, rows) {
  const out = [`| ${head.join(" | ")} |`, `| ${head.map(() => "---").join(" | ")} |`];
  for (const r of rows) out.push(`| ${r.map(esc).join(" | ")} |`);
  return out.join("\n");
}

/** Everything the docs need, from the raw files. Pure: no I/O. */
export function build({ machines, formats, threads, hoops, liloExts }) {
  // 1. Consistency: the formats file must agree with the engine.
  const writable = formats.formats.filter((f) => f.lilo === "read+write").map((f) => f.ext).sort();
  if (JSON.stringify(writable) !== JSON.stringify(liloExts)) {
    throw new Error(
      `data/compat/formats.json says Lilo handles [${writable}] but the engine handles [${liloExts}]. Update formats.json.`,
    );
  }
  const lilo = new Set(liloExts);
  for (const b of machines.brands) {
    for (const m of b.models) {
      const hasLilo = m.formats.some((f) => lilo.has(f));
      const wifi = m.liloWifi === true || m.liloWifi === "untested";
      const want = wifi ? "Wi-Fi + file" : hasLilo ? "file" : "not supported";
      if (m.liloSupport !== want) {
        throw new Error(`${b.name} ${m.name}: liloSupport is "${m.liloSupport}" but its data says "${want}".`);
      }
    }
  }

  const brands = machines.brands.filter((b) => b.models.length > 0);
  const empty = machines.brands.filter((b) => b.models.length === 0);
  const allModels = brands.flatMap((b) => b.models);

  const threadBrands = [...new Set(threads.map((t) => t.brand))].sort((a, b) => a.localeCompare(b));
  const totalColours = threads.reduce((n, t) => n + t.count, 0);
  const hoopList = hoops.hoops;

  const counts = {
    brands: brands.length,
    machines: allModels.length,
    machinesVerified: allModels.filter((m) => m.verified).length,
    wifiCapableUntested: allModels.filter((m) => m.liloWifi === "untested").length,
    wifiTested: allModels.filter((m) => m.liloWifi === true).length,
    threadBrands: threadBrands.length,
    threadLines: threads.length,
    threadColours: totalColours,
    hoops: hoopList.length,
    hoopsVerified: hoopList.filter((h) => h.verified).length,
    formatsReadWrite: liloExts.length,
    formatsListed: formats.formats.length,
  };

  const combined = {
    version: 1,
    compiled: machines.compiled,
    note: machines.note,
    counts,
    liloTestStatus: { wifiTestedOn: [], pending: ["Brother Innov-is NV2700"] },
    formats: formats.formats,
    brands: machines.brands,
    threads: threads.map((t) => ({
      id: t.id, brand: t.brand, line: t.line, label: t.label, count: t.count,
      material: t.material ?? null, weight: t.weight ?? null, licence: t.licence, source: t.source,
    })),
    hoops: hoopList,
    hoopBrands: hoops.brands,
  };

  return { counts, brands, empty, threadBrands, combined };
}

function formatsSection(formats) {
  const rows = formats.formats.map((f) => [
    ext(f.ext),
    f.name,
    f.brands.join(", "),
    yesNo(f.colours),
    f.lilo === "read+write" ? "read + write" : "not supported",
    f.note,
  ]);
  return table(["Ext", "Name", "Brands", "Colour info kept?", "Lilo", "Notes"], rows);
}

function brandSection(b) {
  const lines = [`### ${b.name}`, "", b.summary, ""];
  lines.push(`- Native format: ${b.nativeFormats.length ? b.nativeFormats.map(ext).join(", ") : "none"}`);
  lines.push(`- Also accepted: ${list(b.acceptedFormats.filter((f) => !b.nativeFormats.includes(f)).map(ext))}`);
  lines.push(`- Getting designs on: ${list(b.transferMethods)}`);
  lines.push(`- Official app: ${b.officialApp}`);
  lines.push("");
  const rows = b.models.map((m) => [
    m.name,
    m.type,
    m.formats.map(ext).join(" "),
    ext(m.preferredFormat),
    m.transfer.join(", "),
    wifiLabel(m.liloWifi),
    m.liloSupport,
    m.testStatus,
    m.verified ? "yes" : "UNVERIFIED",
    m.note,
  ]);
  lines.push(
    table(
      ["Model", "Type", "Formats", "Best", "Transfer", "Lilo Wi-Fi", "Lilo support", "Test status", "Verified", "Notes"],
      rows,
    ),
  );
  lines.push("");
  lines.push("Sources (checked " + "2026-10-03" + "):");
  for (const s of b.sources) lines.push(`- ${s.url} (${s.claim})`);
  return lines.join("\n");
}

function threadSection(threads, threadBrands, totalColours) {
  const lines = [
    `Lilo ships ${threads.length} thread lines from ${threadBrands.length} brands, ${totalColours.toLocaleString("en-US")} colours in total.` +
      " Palettes come from Ink/Stitch (GPL-3.0). Weight and material are shown only where the palette file states them.",
    "",
  ];
  const rows = [];
  for (const b of threadBrands) {
    for (const t of threads.filter((x) => x.brand === b).sort((a, c) => a.line.localeCompare(c.line))) {
      rows.push([b, t.line, String(t.count), t.material ?? "", t.weight ?? ""]);
    }
  }
  lines.push(table(["Brand", "Line", "Colours", "Material", "Weight"], rows));
  return lines.join("\n");
}

function hoopSection(hoops) {
  const byBrand = new Map();
  for (const h of hoops.hoops) {
    if (!byBrand.has(h.brand)) byBrand.set(h.brand, []);
    byBrand.get(h.brand).push(h);
  }
  const lines = [
    `${hoops.hoops.length} hoops, ${hoops.hoops.filter((h) => h.verified).length} with a size confirmed from the maker's page. Sewing area is what the needle can reach, width x height.`,
    "",
  ];
  for (const brand of [...byBrand.keys()].sort((a, b) => a.localeCompare(b))) {
    lines.push(`### ${brand}`, "");
    const rows = byBrand
      .get(brand)
      .slice()
      .sort((a, b) => a.widthMm * a.heightMm - b.widthMm * b.heightMm || a.id.localeCompare(b.id))
      .map((h) => [
        h.name,
        `${h.widthMm} x ${h.heightMm}`,
        `${inch(h.widthMm)} x ${inch(h.heightMm)}`,
        h.shape,
        h.machines.join(", "),
        h.verified ? "yes" : "UNVERIFIED",
      ]);
    lines.push(table(["Hoop", "mm", "in", "Shape", "Machines", "Verified"], rows), "");
  }
  return lines.join("\n").trimEnd();
}

export function renderDocs(inputs) {
  const { counts, brands, empty, threadBrands, combined } = build(inputs);
  const { formats, threads, hoops } = inputs;

  const wifiBrands = brands.filter((b) => b.models.some((m) => m.liloWifi === "untested")).map((b) => b.name);

  const notSupported = [];
  for (const f of formats.formats.filter((x) => x.lilo === "none")) {
    notSupported.push(`- **${ext(f.ext)}** (${f.name}): ${f.note}`);
  }
  const unsupportedMachines = brands.flatMap((b) => b.models.filter((m) => m.liloSupport === "not supported").map((m) => `${b.name} ${m.name}`));

  const md = [
    "# Compatibility",
    "",
    "<!-- Generated by scripts/build-compat-docs.mjs from data/compat/*.json. Do not edit by hand: run `pnpm compat`. -->",
    "",
    `Compiled ${combined.compiled}. Lilo is not affiliated with any brand named here; names belong to their owners.`,
    "",
    "**Honest status.** " + WIFI_PENDING + " Nothing below has been run on real hardware yet. 'Verified' means a maker page said it on the compile date; 'UNVERIFIED' means it is from memory, a third party, or a format spec, so check your machine's manual.",
    "",
    `At a glance: ${counts.brands} brands, ${counts.machines} machines (${counts.machinesVerified} checked against a maker page), ${counts.threadLines} thread lines, ${counts.threadColours.toLocaleString("en-US")} colours, ${counts.hoops} hoops.`,
    "",
    "## How Lilo gets designs to your machine",
    "",
    "1. **File.** Export a design in your machine's format and copy it to a USB stick (or send it with the maker's app). This works for every machine that reads one of the formats in the next section.",
    `2. **Wi-Fi with Lilo Link (Brother).** Lilo Link sends a PES to a Brother machine over your home network. It finds the machine by scanning your local /24 network for one that answers Brother's design-transfer API ("pedxml", the one Brother's Design Database Transfer app uses). So in principle any machine that works with Design Database Transfer should show up. ${WIFI_PENDING}`,
    `3. **Baby Lock.** Baby Lock's Wi-Fi models (${brands.find((b) => b.name === "Baby Lock").models.filter((m) => m.liloWifi === "untested").map((m) => m.name).join(", ")}) use Baby Lock's edition of the same Design Database Transfer app, so Lilo Link may find them too. Untested.`,
    "4. **Other brands.** Pfaff, Husqvarna Viking and Singer have their own cloud app (mySewnet), Brother has Artspira, Baby Lock has IQ Intuition Positioning. Lilo does not talk to those. Use a USB stick.",
    "",
    "Lilo never uploads your designs anywhere. Wi-Fi send only goes to a machine on your own network.",
    "",
    "## Supported file formats",
    "",
    `Lilo reads and writes ${counts.formatsReadWrite} formats. File-format round trips are checked against pyembroidery (MIT) by an opt-in test (engine/test/formats-crosscheck.test.ts).`,
    "",
    formatsSection(formats),
    "",
    "## Machines by brand",
    "",
    "Type: home or commercial (multi-needle). 'Lilo Wi-Fi': yes = tested working, untested = looks compatible but Lilo has not run against it, no = no Wi-Fi path with Lilo. 'Lilo support': Wi-Fi + file, file, or not supported.",
    "",
    brands.map(brandSection).join("\n\n"),
    "",
    "## Thread catalogue",
    "",
    threadSection(threads, threadBrands, counts.threadColours),
    "",
    "## Hoops by brand and machine",
    "",
    hoopSection(hoops),
    "",
    "## Not supported, and why",
    "",
    ...notSupported,
    "",
    ...(unsupportedMachines.length ? ["Machines whose only formats Lilo cannot write:", ...unsupportedMachines.map((x) => `- ${x}`), ""] : []),
    ...(empty.length ? [`Brands listed with no models yet: ${empty.map((b) => `${b.name} (${b.summary})`).join(" ")}`, ""] : []),
    "Also not covered: Poolin and other low-cost clones, Bernette beyond the b79, and Wi-Fi apps (mySewnet, Artspira, IQ Intuition Positioning, HappyLAN) which Lilo does not use.",
    "",
    "## Tell us your machine works (or does not)",
    "",
    `[Open a machine report](${ISSUE_URL}). It takes two minutes: your model, the file format you used, how the design got there, and what happened. Wi-Fi reports for Brother and Baby Lock models are the most useful right now.`,
    "",
  ].join("\n");

  const readme = [
    README_START,
    "## Works with",
    "",
    table(
      ["Brand", "File formats the machine takes", "Wi-Fi via Lilo Link"],
      brands.map((b) => {
        const w = b.models.filter((m) => m.liloWifi === "untested").length;
        return [b.name, b.acceptedFormats.map(ext).join(" ") || "-", w ? `Untested (${w} model${w > 1 ? "s" : ""})` : "No"];
      }),
    ),
    "",
    `${counts.brands} brands, ${counts.machines} machines, ${counts.threadLines} thread lines (${counts.threadColours.toLocaleString("en-US")} colours), ${counts.hoops} hoops. Lilo reads and writes ${liloListText(inputs.liloExts)}.`,
    "",
    `**Status: ${WIFI_PENDING}** Wi-Fi-capable models (${wifiBrands.join(", ")}) look compatible but none has been run with Lilo yet. ${counts.machinesVerified} of ${counts.machines} machine entries were checked against a maker page; the rest say UNVERIFIED.`,
    "",
    `Full tables: [docs/compatibility.md](docs/compatibility.md). Got a machine? [Tell us how it went](${ISSUE_URL}).`,
    README_END,
  ].join("\n");

  return { md, compatJson: JSON.stringify(combined, null, 1) + "\n", readmeBlock: readme };
}

function liloListText(exts) {
  return exts.map((e) => e.toUpperCase()).join(", ");
}

/** Put the generated block into README text, replacing the old block (or inserting before "## Develop"). */
export function applyReadme(readme, block) {
  const a = readme.indexOf(README_START);
  const b = readme.indexOf(README_END);
  if (a !== -1 && b !== -1 && b > a) {
    return readme.slice(0, a) + block + readme.slice(b + README_END.length);
  }
  const at = readme.indexOf("\n## Develop");
  if (at === -1) throw new Error('README.md has no "## Develop" heading to insert before.');
  return readme.slice(0, at + 1) + block + "\n" + readme.slice(at);
}

function loadInputs() {
  return {
    machines: json("data/compat/machines.json"),
    formats: json("data/compat/formats.json"),
    threads: json("data/threads/index.json"),
    hoops: json("engine/src/hoops/library.json"),
    liloExts: liloExtensions(read("engine/src/formats/types.ts")),
  };
}

function main() {
  const check = process.argv.includes("--check");
  const out = renderDocs(loadInputs());
  const readmeNow = read("README.md");
  const targets = [
    ["docs/compatibility.md", out.md],
    ["docs/compat.json", out.compatJson],
    ["README.md", applyReadme(readmeNow, out.readmeBlock)],
  ];
  const stale = [];
  for (const [path, text] of targets) {
    const current = existsSync(`${ROOT}${path}`) ? read(path) : null;
    if (current !== text) {
      stale.push(path);
      if (!check) writeFileSync(`${ROOT}${path}`, text);
    }
  }
  if (check) {
    if (stale.length) {
      console.error(`Out of date: ${stale.join(", ")}. Run \`pnpm compat\` and commit the result.`);
      process.exit(1);
    }
    console.log("Compatibility docs are up to date.");
  } else {
    console.log(stale.length ? `Wrote ${stale.join(", ")}.` : "Compatibility docs already up to date.");
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
